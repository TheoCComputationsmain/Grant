-- Grant durable schema for Neon Postgres.
-- Applied automatically by grant/db.py when DATABASE_URL / NEON_DATABASE_URL /
-- GRANT_NEON_DATABASE_URL is configured. Safe to run repeatedly.

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS workspaces (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS gateways (
    token_hash TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    upstream_url TEXT NOT NULL,
    policy_json TEXT NOT NULL,
    workspace TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS requests (
    id TEXT PRIMARY KEY,
    token TEXT UNIQUE NOT NULL,
    agent TEXT NOT NULL,
    action TEXT NOT NULL,
    summary TEXT NOT NULL,
    scope_json TEXT NOT NULL,
    scope_hash TEXT NOT NULL,
    requester TEXT NOT NULL,
    workspace TEXT NOT NULL,
    callback_url TEXT NOT NULL,
    channel TEXT NOT NULL DEFAULT 'browser_popup',
    gateway_hash TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    status TEXT NOT NULL,
    decision TEXT,
    decision_at TEXT,
    policy TEXT
);

CREATE TABLE IF NOT EXISTS permissions (
    id TEXT PRIMARY KEY,
    workspace TEXT NOT NULL,
    agent TEXT NOT NULL,
    action TEXT NOT NULL,
    scope_hash TEXT NOT NULL,
    policy TEXT NOT NULL,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    source_request TEXT NOT NULL,
    signature TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS billing_contacts (
    org_id TEXT PRIMARY KEY,
    email TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS plans (
    org_id TEXT PRIMARY KEY,
    tier TEXT NOT NULL,
    status TEXT NOT NULL,
    trial_tier TEXT,
    trial_ends_at TEXT,
    plan_expires_at TEXT,
    quota_reset_at TEXT,
    checkout_id TEXT NOT NULL,
    customer_ref TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS usage_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id TEXT NOT NULL,
    request_id TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS billing_events (
    event_id TEXT PRIMARY KEY,
    org_id TEXT NOT NULL,
    tier TEXT NOT NULL,
    status TEXT NOT NULL,
    applied_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS unclaimed_payments (
    event_id TEXT PRIMARY KEY,
    payment_ref TEXT NOT NULL,
    email TEXT NOT NULL,
    tier TEXT NOT NULL,
    paid_at TEXT NOT NULL,
    status TEXT NOT NULL,
    workspace TEXT NOT NULL,
    created_at TEXT NOT NULL,
    claimed_at TEXT
);

CREATE TABLE IF NOT EXISTS renewal_reminders (
    reminder_key TEXT PRIMARY KEY,
    org_id TEXT NOT NULL,
    tier TEXT NOT NULL,
    due_at TEXT NOT NULL,
    plan_expires_at TEXT NOT NULL,
    form_url TEXT NOT NULL,
    status TEXT NOT NULL,
    sent_at TEXT,
    created_at TEXT NOT NULL
);

-- Telemetry. Raw IP addresses and device identifiers are never stored; only
-- salted SHA-256 hashes. `email` is the normalized account email and is never
-- returned by any stats endpoint.
CREATE TABLE IF NOT EXISTS login_history (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    email TEXT,
    ip_hash TEXT NOT NULL,
    device_hash TEXT NOT NULL,
    user_agent TEXT,
    session_id TEXT NOT NULL,
    source TEXT NOT NULL DEFAULT 'workspace',
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS popup_impressions (
    id TEXT PRIMARY KEY,
    request_id TEXT NOT NULL,
    org_id TEXT NOT NULL,
    channel TEXT NOT NULL,
    device_hash TEXT NOT NULL,
    user_agent TEXT,
    opened_at TEXT NOT NULL,
    decision TEXT,
    approver_hash TEXT
);

CREATE INDEX IF NOT EXISTS idx_billing_contacts_email ON billing_contacts(email);
CREATE INDEX IF NOT EXISTS idx_unclaimed_email ON unclaimed_payments(email, status);
CREATE INDEX IF NOT EXISTS idx_unclaimed_ref ON unclaimed_payments(payment_ref, status);
CREATE INDEX IF NOT EXISTS idx_renewal_due ON renewal_reminders(status, due_at);
CREATE INDEX IF NOT EXISTS idx_requests_workspace ON requests(workspace, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_permissions_agent ON permissions(agent, expires_at);
CREATE INDEX IF NOT EXISTS idx_permissions_source ON permissions(source_request);
CREATE INDEX IF NOT EXISTS idx_usage_org_created ON usage_events(org_id, created_at);
CREATE INDEX IF NOT EXISTS idx_login_created ON login_history(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_user ON login_history(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_session ON login_history(session_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_popup_opened ON popup_impressions(opened_at DESC);
CREATE INDEX IF NOT EXISTS idx_popup_request ON popup_impressions(request_id);
CREATE INDEX IF NOT EXISTS idx_popup_device ON popup_impressions(device_hash);
